-- Rassah schema v1. Source of truth for the database (docs/stack/04 describes it).
-- Apply in the Supabase SQL editor (paste this file) or with `supabase db push`.
-- All access is server-side with the service-role key; RLS is on with no public policies.

-- ===== Mock store (synthetic data modeled on Saudi store pages) =====
create table if not exists products (
  id           text primary key,              -- 'p-07'
  name         text not null,
  description  text not null,                 -- page text given to Gemini
  url          text,                          -- illustrative only
  category     text,
  source_hash  text not null                  -- sha256(name || '\n' || description)
);

create table if not exists cartons (
  id            text primary key,             -- 'S','M','L','XL','FLAT'
  name          text not null,
  inner_l_cm    numeric not null,
  inner_w_cm    numeric not null,
  inner_h_cm    numeric not null,
  max_weight_g  numeric not null,
  tare_g        numeric not null default 0,
  cost_sar      numeric not null              -- synthetic
);

create table if not exists shipping_rates (
  id                  int primary key default 1 check (id = 1),  -- single row
  base_sar            numeric not null,       -- synthetic, covers the first kg
  per_kg_sar          numeric not null,       -- synthetic, each additional started kg
  volumetric_divisor  numeric not null        -- cm^3 per kg
);

create table if not exists orders (
  id          text primary key,               -- '1045'
  demo        text,                           -- demo label, if used in the pitch
  expect      text,                           -- intended scenario (documentation)
  created_at  timestamptz not null default now()
);

create table if not exists order_items (
  order_id    text references orders(id) on delete cascade,
  product_id  text references products(id),
  qty         int  not null check (qty between 1 and 12),
  primary key (order_id, product_id)
);

-- ===== AI catalog cache =====
create table if not exists product_facts (
  product_id     text primary key references products(id) on delete cascade,
  length_cm      numeric,
  width_cm       numeric,
  height_cm      numeric,                     -- natural upright orientation
  weight_g       numeric,
  dims_source    text not null check (dims_source   in ('page','inferred','manual','unknown')),
  weight_source  text not null check (weight_source in ('page','inferred','manual','unknown')),
  fragile        boolean not null,
  liquid         boolean not null,
  sensitive      boolean not null,
  confidence     text check (confidence in ('high','medium','low')),
  evidence       text,
  origin         text not null check (origin in ('ai','manual','ai_corrected')),
  source_hash    text not null,               -- staleness check against products.source_hash
  model          text,
  prompt_version text,
  extracted_at   timestamptz,
  updated_at     timestamptz not null default now()
);

-- ===== Monitoring events =====
create table if not exists extraction_events (
  id               uuid primary key default gen_random_uuid(),
  created_at       timestamptz not null default now(),
  run_id           uuid,                      -- order_runs.id (null for admin/eval)
  trigger          text not null check (trigger in ('order','admin','eval')),
  product_id       text not null,
  status           text not null check (status in ('ok','parse_error','api_error','rate_limited','timeout','blocked','empty','config_error','simulated_outage')),
  latency_ms       int,
  input_tokens     int,
  output_tokens    int,
  thinking_tokens  int,
  cost_usd         numeric,
  model            text,
  prompt_version   text,
  dims_source      text,
  weight_source    text,
  confidence       text,
  fragile          boolean,
  liquid           boolean,
  error_code       text,
  error_message    text
);
create index if not exists extraction_events_created_at_idx on extraction_events (created_at desc);
create index if not exists extraction_events_run_id_idx on extraction_events (run_id);

create table if not exists order_runs (
  id                   uuid primary key,      -- generated by the app at request start (run_id)
  created_at           timestamptz not null default now(),
  trigger              text not null check (trigger in ('order','eval')),
  order_id             text not null,
  status               text not null check (status in ('box_found','no_box','needs_measurement','error')),
  carton_id            text,
  strategy             text,
  items_count          int,
  cache_hits           int,
  cache_misses         int,
  estimated_units      int,                   -- units packed with inferred dimensions
  unit_sources         jsonb,                 -- {"page":n,"inferred":n,"manual":n,"unknown":n}
  ai_products          jsonb,                 -- product ids whose facts were AI-extracted at pack time (M1 denominator)
  extract_ms           int,
  pack_ms              int,
  total_ms             int,
  candidates_checked   int,
  attempts             jsonb,                 -- [{cartonId, outcome, strategy}]
  validator_rejections int not null default 0,
  violations           jsonb,                 -- [{code, unitId, cartonId, detail}]
  carton_cost_sar      numeric,
  shipping_sar         numeric,
  total_sar            numeric,
  tokens_total         int,
  cost_usd             numeric,
  engine_version       text,
  prompt_version       text,
  monitoring_degraded  boolean not null default false,
  error_code           text,
  employee_action      text not null default 'pending' check (employee_action in ('pending','confirmed','edited')),
  action_at            timestamptz
);
create index if not exists order_runs_created_at_idx on order_runs (created_at desc);

create table if not exists corrections (
  id           uuid primary key default gen_random_uuid(),
  created_at   timestamptz not null default now(),
  run_id       uuid references order_runs(id) on delete set null,
  product_id   text not null references products(id) on delete cascade,
  field        text not null,                 -- 'height_cm', 'fragile', ...
  old_value    text,
  new_value    text,
  prior_origin text not null                  -- 'ai' counts toward the AI correction rate
);
create index if not exists corrections_run_id_idx on corrections (run_id);

create table if not exists alerts (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  rule        text not null,                  -- 'M6_gemini_failure_rate'
  severity    text not null check (severity in ('info','warning','critical')),
  value       numeric,
  threshold   numeric,
  sample_size int,
  message     text,
  simulated   boolean not null default false, -- raised by demo fault injection
  resolved_at timestamptz
);
create index if not exists alerts_open_idx on alerts (rule) where resolved_at is null;

-- ===== Offline evaluation =====
create table if not exists eval_runs (
  id             uuid primary key default gen_random_uuid(),
  created_at     timestamptz not null default now(),
  kind           text not null check (kind in ('extraction','packing')),
  model          text,
  prompt_version text,
  engine_version text,
  summary        jsonb not null
);

create table if not exists eval_results (
  id          uuid primary key default gen_random_uuid(),
  eval_run_id uuid not null references eval_runs(id) on delete cascade,
  case_id     text not null,
  passed      boolean,
  details     jsonb not null
);

