-- Demo store schema. Run in the DEMO STORE's own Supabase project, never in Rassah's.
-- Order numbers start at 5001 so they are easy to tell apart from Rassah's seeded orders (1001–1020).

create table if not exists store_orders (
  id            bigint generated by default as identity (start with 5001) primary key,
  created_at    timestamptz not null default now(),
  customer_name text
);

create table if not exists store_order_items (
  order_id   bigint not null references store_orders(id) on delete cascade,
  product_id text   not null,
  qty        int    not null check (qty between 1 and 12),
  primary key (order_id, product_id)
);

-- Server-only access with the service-role key; no public policies.
alter table store_orders      enable row level security;
alter table store_order_items enable row level security;
